	if [ -n "$LOCAL_BINARY" ]; then
		[ -f "$LOCAL_BINARY" ] || die "$(t err_local_missing "$LOCAL_BINARY")"
		DOWNLOADED_BINARY="$LOCAL_BINARY"
		chmod 0755 "$DOWNLOADED_BINARY"
		step "$(t step_local_binary "$LOCAL_BINARY")"
	elif ! release_arch_supported; then
		die "$(t err_release_arch "$ARCH")"
	else
