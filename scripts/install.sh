	if [ "$HAS_SYSTEMD" = "1" ] && ! systemctl is-active --quiet corefusion; then
		printf '%s\n' "$LOG_NOW" | tail -n 30 >&2
		die "$(t err_systemd_not_running)"
	fi
	warn "$(t warn_ready_timeout)"
fi

