#!/usr/bin/env python3
"""Generate the embedded install.sh message catalogs.

Source of truth: scripts/install-i18n/{zh,en,fa,ru}.json
The generated block is injected between the INSTALL_I18N markers in
scripts/install.sh, so the installer remains a single self-contained file
that works with `curl ... | bash`.

Usage:
    python3 scripts/gen-install-i18n.py
    python3 scripts/gen-install-i18n.py --check
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
I18N_DIR = ROOT / "scripts" / "install-i18n"
INSTALL_SH = ROOT / "scripts" / "install.sh"
LANGUAGES = ("zh", "en", "fa", "ru")
BEGIN = "# >>> INSTALL_I18N_BEGIN (generated by scripts/gen-install-i18n.py; do not edit)\n"
END = "# <<< INSTALL_I18N_END\n"


def load_catalogs() -> dict[str, dict]:
    catalogs = {}
    for lang in LANGUAGES:
        path = I18N_DIR / f"{lang}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        if data.get("language") != lang:
            raise SystemExit(f"{path}: language mismatch")
        catalogs[lang] = data

    keys = list(catalogs["zh"]["messages"])
    usage_len = len(catalogs["zh"]["usage"])
    for lang, data in catalogs.items():
        if list(data["messages"]) != keys:
            raise SystemExit(f"{lang}: message keys/order differ from zh")
        if len(data["usage"]) != usage_len:
            raise SystemExit(f"{lang}: usage line count differs from zh")
        for key, value in data["messages"].items():
            if "\n" in value or "\r" in value:
                raise SystemExit(f"{lang}.{key}: message must be single-line")
            expected = catalogs["zh"]["messages"][key].count("%s")
            actual = value.count("%s")
            if actual != expected:
                raise SystemExit(
                    f"{lang}.{key}: placeholder count {actual} != zh {expected}"
                )
    return catalogs


def catalog_block(catalogs: dict[str, dict]) -> str:
    keys = list(catalogs["zh"]["messages"])
    out: list[str] = []
    for lang in LANGUAGES:
        out.append(f"catalog_{lang}() {{")
        out.append("\tcat <<'EOF'")
        for key in keys:
            out.append(f"{key}={catalogs[lang]['messages'][key]}")
        out.append("EOF")
        out.append("}")
        out.append("")
    return "\n".join(out)


def usage_block(catalogs: dict[str, dict]) -> str:
    out: list[str] = ["usage_text() {", "\tcase \"$LANG_CODE\" in"]
    for lang in ("en", "fa", "ru"):
        out.append(f"\t\t{lang})")
        out.append("\t\t\tcat <<'EOF'")
        out.extend(catalogs[lang]["usage"])
        out.append("EOF")
        out.append("\t\t\t;;")
    out.append("\t\t*)")
    out.append("\t\t\tcat <<'EOF'")
    out.extend(catalogs["zh"]["usage"])
    out.append("EOF")
    out.append("\t\t\t;;")
    out.append("\tesac")
    out.append("}")
    return "\n".join(out)


def generated(catalogs: dict[str, dict]) -> str:
    return catalog_block(catalogs) + "\n" + usage_block(catalogs)


def main() -> int:
    check = "--check" in sys.argv[1:]
    text = INSTALL_SH.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit("INSTALL_I18N markers not found in scripts/install.sh")
    begin_idx = text.index(BEGIN) + len(BEGIN)
    end_idx = text.index(END)
    block = generated(load_catalogs())
    new_text = text[:begin_idx] + "\n" + block + "\n" + text[end_idx:]
    if check:
        if new_text != text:
            print("scripts/install.sh is out of date; run python3 scripts/gen-install-i18n.py", file=sys.stderr)
            return 1
        print("install.sh i18n block is up to date")
        return 0
    INSTALL_SH.write_text(new_text, encoding="utf-8")
    print(f"updated {INSTALL_SH} ({len(block.splitlines())} generated lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
