normalize_lang() {
	local v="${1:-}"
	v="${v,,}"
	case "$v" in
		zh|zh_*|zh-*|*_cn|*_sg|*hans*) echo "zh" ;;
		en|en_*|en-*) echo "en" ;;
		fa|fa_*|fa-*) echo "fa" ;;
		ru|ru_*|ru-*) echo "ru" ;;
		*) return 1 ;;
	esac
}

load_messages() {
	local data="" k v
	case "$LANG_CODE" in
		en) data="$(catalog_en)" ;;
		fa) data="$(catalog_fa)" ;;
		ru) data="$(catalog_ru)" ;;
		*)  data="$(catalog_zh)" ;;
	esac
	MSG=()
	while IFS='=' read -r k v; do
		[ -n "$k" ] || continue
		MSG["$k"]="$v"
	done <<< "$data"
}

# 轻量占位符替换：只替换 %s，不把文案中的其它 % 当作 printf 格式符
t() {
	local key="$1"; shift
	local fmt="${MSG[$key]:-$key}"
	local out="" arg
	while [ "$#" -gt 0 ]; do
		case "$fmt" in
			*%s*)
				out+="${fmt%%\%s*}"
				out+="$1"
				fmt="${fmt#*\%s}"
				shift
				;;
			*) break ;;
		esac
	done
	out+="$fmt"
	printf '%s' "$out"
}

