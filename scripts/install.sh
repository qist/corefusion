pkg_refresh() {
	case "$FAMILY" in
		debian) export DEBIAN_FRONTEND=noninteractive; apt-get update -y -qq ;;
		rhel)   if command -v dnf >/dev/null 2>&1; then dnf -q makecache -y; else yum -q makecache -y; fi ;;
		alpine) apk update -q ;;
		arch)   pacman -Sy --noconfirm --quiet ;;
		suse)   zypper -q refresh ;;
	esac
}

pkg_install() {
	case "$FAMILY" in
		debian) DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends "$@" ;;
		rhel)   if command -v dnf >/dev/null 2>&1; then dnf install -y -q "$@"; else yum install -y -q "$@"; fi ;;
		alpine) apk add --no-cache -q "$@" ;;
		arch)   pacman -S --needed --noconfirm --quiet "$@" ;;
		suse)   zypper -q install -y --no-recommends "$@" ;;
		*)      return 1 ;;
	esac
}

install_deps() {
	[ "$SKIP_DEPS" = "1" ] && { warn "$(t warn_skip_deps)"; return 0; }

	local base_pkgs=()
	local runtime_pkgs=()
	case "$FAMILY" in
		debian)
			base_pkgs=(curl ca-certificates tar gzip xz-utils tzdata)
			runtime_pkgs=(nftables iproute2 iptables conntrack kmod procps lsof openssl passwd)
			;;
		rhel)
			base_pkgs=(curl ca-certificates tar gzip xz tzdata)
			runtime_pkgs=(nftables iproute conntrack-tools kmod procps-ng lsof openssl shadow-utils)
			# EL8+ 的 iptables 命令由 iptables-nft 提供（没有独立的 iptables 包）；
			# EL7 反过来只有 iptables。装错包名会整批失败，必须按主版本区分。
			case "${OS_VER%%.*}" in
				7) runtime_pkgs+=(iptables) ;;
				*) runtime_pkgs+=(iptables-nft) ;;
			esac
			;;
		alpine)
			base_pkgs=(curl ca-certificates tar gzip xz tzdata)
			runtime_pkgs=(nftables iproute2 iptables conntrack-tools kmod procps lsof openssl shadow)
			;;
		arch)
			base_pkgs=(curl ca-certificates tar gzip xz tzdata)
			runtime_pkgs=(nftables iproute2 iptables conntrack-tools kmod procps-ng lsof openssl shadow)
			;;
		suse)
			base_pkgs=(curl ca-certificates tar gzip xz tzdata)
			runtime_pkgs=(nftables iproute2 iptables conntrack-tools kmod procps lsof openssl shadow)
			;;
		*)
			base_pkgs=(curl ca-certificates tar gzip xz)
			;;
	esac

	local build_pkgs=()
	if [ "$MODE" = "source" ]; then
		case "$FAMILY" in
			debian) build_pkgs=(git build-essential) ;;
			rhel)   build_pkgs=(git gcc gcc-c++ make) ;;
			alpine) build_pkgs=(git build-base) ;;
			arch)   build_pkgs=(git base-devel) ;;
			suse)   build_pkgs=(git gcc gcc-c++ make) ;;
		esac
	fi

	step "$(t step_deps "$FAMILY")"
	if ! pkg_refresh; then
		warn "$(t warn_pkg_refresh)"
	fi
	if ! pkg_install "${base_pkgs[@]}" ${build_pkgs[@]+"${build_pkgs[@]}"}; then
		warn "$(t warn_base_pkgs)"
	fi
	# 运行时依赖是“可选增强”：不能和基础包放在同一次事务里，
	# 否则某个包在旧发行版仓库不存在（如 RHEL7 无 nftables）会连 curl/tar 都装不上。
	if [ "${#runtime_pkgs[@]}" -gt 0 ]; then
		if ! pkg_install "${runtime_pkgs[@]}" >/dev/null 2>&1; then
			warn "$(t warn_runtime_batch)"
			for p in "${runtime_pkgs[@]}"; do
				pkg_install "$p" >/dev/null 2>&1 || true
			done
		fi
	fi

	local missing=()
	for c in curl tar gzip; do command -v "$c" >/dev/null 2>&1 || missing+=("$c"); done
	if [ "$MODE" = "source" ]; then
		for c in git make; do command -v "$c" >/dev/null 2>&1 || missing+=("$c"); done
	fi
	[ "${#missing[@]}" -eq 0 ] || die "$(t err_missing_cmds "${missing[*]}")"

	# 运行时能力自检：nft/tc 缺失不阻断安装（面板其余功能可用），但要明确告诉用户
	local caps_missing=()
	for c in nft tc ip ss pgrep pkill lsof openssl modprobe conntrack; do
		command -v "$c" >/dev/null 2>&1 || caps_missing+=("$c")
	done
	if [ "${#caps_missing[@]}" -gt 0 ]; then
		warn "$(t warn_caps_missing "${caps_missing[*]}")"
		warn "$(t warn_caps_hint)"
	else
		ok "$(t ok_runtime)"
	fi
	ok "$(t ok_deps)"
}

# ── 源码模式依赖版本选择 ─────────────────────────────────────
# 纯 shell 版本比较：ver_ge A B 表示 A >= B（支持 1.27 / 1.27.3 / 22.14.0）
ver_ge() {
	local IFS=.
	local -a A=($1) B=($2)
	local n=${#A[@]} i x y
	[ "${#B[@]}" -gt "$n" ] && n=${#B[@]}
	for ((i = 0; i < n; i++)); do
		x="${A[i]:-0}"; y="${B[i]:-0}"
		x="${x%%[!0-9]*}"; y="${y%%[!0-9]*}"
		x="${x:-0}"; y="${y:-0}"
		if ((10#$x > 10#$y)); then return 0; fi
		if ((10#$x < 10#$y)); then return 1; fi
	done
	return 0
}

req_go_version() {
	local v="" tc=""
	if [ -f "$PWD/go.mod" ]; then
		v="$(awk '/^go [0-9]/{print $2; exit}' go.mod)"
		tc="$(awk '/^toolchain go/{sub(/^toolchain go/, ""); print; exit}' go.mod)"
	fi
	echo "${CF_GO_VERSION:-${tc:-${v:-1.27}}}"
}

go_dl_base() { printf '%s' "${CF_GO_MIRROR:-https://go.dev/dl}" | sed 's#/*$##'; }

system_go_ok() {
	command -v go >/dev/null 2>&1 || return 1
	local cur
	cur="$(go env GOVERSION 2>/dev/null | sed 's/^go//')"
	[ -n "$cur" ] || return 1
	ver_ge "$cur" "$1"
}

resolve_go_release() {
	local req="$1" meta ver
	# toolchain 指令可能已是完整版本（x.y.z），直接用；否则查该 minor 的最新补丁
	if printf '%s' "$req" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$'; then
		echo "go${req}"
		return 0
	fi
	meta="$(curl -fsSL --max-time 20 "$(go_dl_base)/?mode=json" 2>/dev/null || true)"
	ver="$(printf '%s' "$meta" | grep -o "\"go${req}\.[0-9]*\"" | head -n1 | tr -d '"' || true)"
	[ -n "$ver" ] || ver="go${req}.0"
	echo "$ver"
}

ensure_go() {
	local req ver tarball
	req="$(req_go_version)"
	if system_go_ok "$req"; then
		ok "$(t ok_system_go "$(go env GOVERSION)" "$req")"
		return 0
	fi

	ver="$(resolve_go_release "$req")"
	tarball="${ver}.linux-$(go_arch).tar.gz"
	step "$(t step_install_go "${ver#go}" "$req")"
	mkdir -p "$TC_DIR"
	local tmp
	tmp="$(mktemp -d)"
	curl -fL --retry 3 --connect-timeout 15 -o "$tmp/go.tgz" "$(go_dl_base)/$tarball" \
		|| die "$(t err_go_download "$tarball")"
	rm -rf "$TC_DIR/go"
	tar -C "$TC_DIR" -xzf "$tmp/go.tgz"
	rm -rf "$tmp"
	export PATH="$TC_DIR/go/bin:$PATH"
	export GOROOT="$TC_DIR/go"
	ok "$(t ok_go "$(go env GOVERSION)")"
}

